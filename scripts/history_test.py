#!/usr/bin/env python3
"""scripts/history_test.py -- keeps the HistoryTest/ folder: the record of tests done on this repository (TEST TOOLING).

Purpose: HistoryTest/ is an archive, not a product feature. Every test run that matters (unit tests in the cloud,
Docker runs on the test PC, real-model runs, scans) gets one folder under HistoryTest/runs/ with a plain-language
description, its command, environment, results, logs, the test project it started from, the finished project it
ended with and a checksum list, so anyone can go back, read it and check that nothing was changed afterwards. This
script packs such a folder, keeps HistoryTest/INDEX.csv and checks the folders. The layout is the one CLAUDE.md
Section 9 asks for; HistoryTest/README.md explains it for readers.

Where it fits: plain repository tooling next to the other scripts in scripts/. Nothing in the gateways, nodes or web
app reads HistoryTest/ or this script.

Inputs / trust boundary: a command to run (given by the developer on the command line), and files to copy in (logs,
project folders, artifacts). Copied material is treated as untrusted DATA: it is never executed, imported or parsed
beyond text redaction and a text diff. Output: one folder HistoryTest/runs/<date>_<time>Z_<area>_<commit>/ with RUN.md,
manifest.json, command.txt, environment.md, results/, logs/, projects/{input,output,diff.patch}, artifacts/, NOTES.md.

Security controls:
- No shell: the wrapped command is an argument list (CWE-78).
- Copy rules: regular files only, symlinks never followed (CWE-59); relative names are checked against an allow-list
  and can not leave the run folder (CWE-22); secret-looking files (.env, keys, certificates stores) and model weights
  are never copied (CWE-312, CWE-540); size limits per file and per run (CWE-400).
- Redaction: text is scrubbed of private keys, bearer tokens, NAME=value secrets, well-known token prefixes, e-mail
  addresses and personal home folder names before it is stored (CWE-532). Redaction is best effort: read what you
  commit. `verify` scans again and fails when a stored file still matches a secret pattern.
- No host name, user name or IP address is recorded. Only OS family and Python version.
- Integrity: SHA-256 (FIPS 180-4, NIST SC-13) of every stored file in manifest.json, and each manifest names the
  run before it with that run's manifest checksum (a chain; two branches may continue from the same run, as Git
  commits do). `verify` detects changed, missing and added files and broken links. The archive is append-only: a
  wrong run is marked with INVALID.md, never edited or deleted; `verify --base <git ref>` fails when an existing
  run was changed. Checksums show accidental or partial changes; the Git history shows who changed what and when.
  The records are not signed.
- INDEX.csv cells are guarded against spreadsheet formula injection (CWE-1236).
Dependencies: Python standard library only (3.9+). No third-party packages, so there is nothing to check for CVEs.

Usage (see docs/commands/history-test.md):
  python3 scripts/history_test.py run  --area go-gateway --kind unit --title "Go gateway unit tests" -- go test ./...
  python3 scripts/history_test.py add  --area autopilot-e2e --kind e2e --where pc --result pass --log ap9.log ...
  python3 scripts/history_test.py invalidate 2026-11-11_084500Z_go-gateway_d15c219 --reason "ran on a stale image"
  python3 scripts/history_test.py verify [--base origin/main]
  python3 scripts/history_test.py index | list
Exit codes: 0 ok (for `run`: recorded, whatever the test result; use --strict to pass the test's failure on),
1 verify found a problem (or --strict and the test failed), 2 bad usage or could not run.
"""
