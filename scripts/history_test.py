# SECURITY: allow-list for names that become part of a path (CWE-22). Lower case, digits, dot, dash, underscore.
NAME_RE = re.compile(r"^[a-z0-9][a-z0-9._-]{0,39}$")
COMMIT_RE = re.compile(r"^[0-9a-f]{7,40}$")
ID_RE = re.compile(r"^\d{4}-\d{2}-\d{2}_\d{6}Z_[a-z0-9][a-z0-9._-]{0,39}_[0-9a-f]{7}(-\d+)?$")
# Outside the manifest: the manifest itself and the two dated additions a finished run may still receive.
UNMANIFESTED = ("manifest.json", "INVALID.md", "NOTES.md")
# SECURITY: allow-list for one path segment of a copied file; anything else is skipped and listed (CWE-22).
SEG_RE = re.compile(r"^[A-Za-z0-9._@+=, ()\[\]-]{1,120}$")
MAX_REL_PATH = 170  # keeps the repository usable on Windows (260 character path limit)

# SECURITY: never copied, whatever the size: secrets (CWE-312) and files that are useless in a history (model weights).
SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", "venv", "target", ".pytest_cache", ".mypy_cache",
             ".cache", ".tox", ".gradle", ".next"}
WEIGHTS_RE = re.compile(r"\.(gguf|safetensors|onnx|ckpt|pth|pt|tflite|mlmodel|iso|qcow2|vmdk|vdi)$", re.I)
SKIP_FILE_RE = re.compile(
    r"(^\.env($|\.)|\.env$|^id_(rsa|dsa|ecdsa|ed25519)|\.(key|pem|p12|pfx|jks|keystore|kdbx|pyc)$"
    r"|^cosign\.(key|pub)$|^\.netrc$|^\.npmrc$|^\.pypirc$|^credentials(\.json)?$)", re.I)

# SECURITY: redaction rules (CWE-532). Each is (name, compiled pattern, replacement). Order matters: blocks first.
# The {0,40} bounds keep matching linear on long tokens (ReDoS, CWE-1333).
# Any setting whose name says secret, token, password, credential, seed or salt, or ends in a _KEY / -KEY part
# (GATEWAY_SIGNING_KEY, x-api-key, node_key_file). Over-matching is accepted: a blanked path harms nobody.
_SECRET_NAME = (r"[A-Za-z0-9_.-]{0,40}(?:SECRET|TOKEN(?!S)|PASSWORD|PASSWD|PASSPHRASE|CREDENTIAL|API_?KEY|ADMIN_?KEY"
                r"|PRIVATE_?KEY|SIGNING_?KEY|[_-]KEYS?(?![A-Za-z])|[_-]SEED(?![A-Za-z])|[_-]SALT(?![A-Za-z]))"
                r"[A-Za-z0-9_.-]{0,40}")
RULES = [
    ("private-key", re.compile(r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----.*?-----END [A-Z0-9 ]*PRIVATE KEY-----", re.S),
     "[REDACTED:private-key]"),
    # A bearer value must hold a digit, so prose such as "Bearer authentication" stays readable.
    ("token", re.compile(r"(?i)\b(bearer)\s+(?!\[REDACTED)(?=[A-Za-z0-9._~+/=-]*[0-9])[A-Za-z0-9._~+/=-]{8,}"),
     r"\1 [REDACTED:token]"),
    ("token", re.compile(r"(?i)\b(authorization[\"']?\s*[:=]\s*[\"']?basic)\s+(?!\[REDACTED)[A-Za-z0-9+/=]{8,}"),
     r"\1 [REDACTED:token]"),
    ("cookie", re.compile(r"(?i)\b((?:set-)?cookie[\"']?\s*[:=]\s*[\"']?)(?!\[REDACTED)[^\s\"';]{8,}[^\r\n\"']*"),
     r"\1[REDACTED:cookie]"),
    ("token", re.compile(
        r"\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{20,}|\bgithub_pat_[A-Za-z0-9_]{20,}|\bsk-[A-Za-z0-9_-]{20,}"
        r"|\bhf_[A-Za-z0-9]{20,}|\bAKIA[0-9A-Z]{16}\b|\bxox[baprs]-[A-Za-z0-9-]{10,}|\bdckr_pat_[A-Za-z0-9_-]{20,}"),
     "[REDACTED:token]"),
    # NAME=value and "name": "value". The value must be 8+ characters and not a plain number, a boolean or an
    # already redacted mark, so `max_tokens=4096` and `token_count: 12` stay readable.
    # Names that say public (gateway_public_key_hex, NODE_PUBKEY_FILE, GPG_KEY = the public key id in Python images) stay.
    ("secret", re.compile(
        r"(?i)(\b(?![A-Za-z0-9_.-]{0,40}(?:PUB|GPG))" + _SECRET_NAME + r"\b[\"']?\s*[=:]\s*[\"']?)(?!\[REDACTED)(?!\d+(?:\.\d+)?\b)"
        r"(?!(?:true|false|null|none)\b)([^\s\"',;&<>]{8,})"), r"\1[REDACTED:secret]"),
    ("password", re.compile(r"(?i)\b([a-z][a-z0-9+.-]*://[^\s:/@]+):(?!\[REDACTED)([^\s@/]{3,})@"),
     r"\1:[REDACTED:password]@"),
    ("email", re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}\b"), "[REDACTED:email]"),
    ("username", re.compile(r"(?i)\b([a-z]:[\\/]+Users[\\/]+)(?!\[REDACTED)[^\\/\s\"'<>|:]+"), r"\1[REDACTED:username]"),
    ("username", re.compile(r"(/Users/|/home/)(?!user\b|\[REDACTED)[A-Za-z0-9._-]+"), r"\1[REDACTED:username]"),
    # RFC 1918 private IPv4 addresses (loopback and documentation ranges are not private and stay).
    ("private-ip", re.compile(r"(?<![\d.])(?:10\.\d{1,3}|192\.168|172\.(?:1[6-9]|2\d|3[01]))\.\d{1,3}\.\d{1,3}(?![\d.])"),
     "[REDACTED:private-ip]"),
]
# Rules whose match in a STORED file makes `verify` fail (the privacy rules above only warn the packer).
HARD_RULES = ("private-key", "token", "cookie", "secret", "password")


def die(msg, code=2):
    """Print an error and exit. Messages never contain file content (CWE-209)."""
    print("history_test: " + msg, file=sys.stderr)
    raise SystemExit(code)


def redact(text, extra=()):
    """Scrub secrets and personal details from text, leaving `[REDACTED:<type>]` marks.

    Args: text (str); extra (iterable of str): literal words to blank as well (for example a machine name).
    Returns: (clean_text, {type: count}).
    Security: best-effort defence against secrets and personal data reaching the repository (CWE-532, CWE-200).
    """
    counts = {}
    for name, pat, repl in RULES:
        text, n = pat.subn(repl, text)
        if n:
            counts[name] = counts.get(name, 0) + n
    for word in extra:
        if len(word) >= 3:  # shorter words would shred the text
            text, n = re.subn(re.escape(word), "[REDACTED:hostname]", text, flags=re.I)
            if n:
                counts["hostname"] = counts.get("hostname", 0) + n
    return text, counts


def hard_hits(text):
    """Return the types of secret rules that still match text (used by verify on stored files)."""
    return sorted({name for name, pat, _ in RULES if name in HARD_RULES and pat.search(text)})


def sha256_file(path):
    """SHA-256 of a file, read in blocks (SECURITY: approved hash, NIST SC-13; bounded memory, CWE-400)."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def is_text(data):
    """True when data looks like UTF-8 text (no NUL byte, decodes)."""
    if b"\x00" in data:
        return False
    try:
        data.decode("utf-8")
        return True
    except UnicodeDecodeError:
        return False


def git(args, cwd=ROOT):
    """Run a read-only git command; returns stdout or '' (SECURITY: fixed argument list, no shell, CWE-78)."""
    try:
        p = subprocess.run(["git"] + args, cwd=cwd, capture_output=True, text=True, timeout=60)
        return p.stdout.strip() if p.returncode == 0 else ""
    except (OSError, subprocess.SubprocessError):
        return ""


def write_text(path, text):
    """Write a UTF-8 text file with LF line ends (the same bytes on every OS, so checksums agree)."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text if text.endswith("\n") else text + "\n")


