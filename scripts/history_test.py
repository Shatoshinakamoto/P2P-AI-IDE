class Packer:
    """Collects files into one run folder, applying the copy rules, limits and redaction.

    Security: every file goes through `store`, the single place that enforces name checks (CWE-22), the no-symlink
    rule (CWE-59), the skip list (CWE-312), the size limits (CWE-400) and redaction (CWE-532).
    """

    def __init__(self, dest, max_file, max_run, extra):
        self.dest, self.max_file, self.max_run, self.extra = dest, max_file, max_run, tuple(extra)
        self.total = 0
        self.skipped, self.shortened, self.redactions = [], [], {}

    def clean(self, text):
        """Redact a piece of text given on the command line (titles, notes, commands)."""
        return redact(text or "", self.extra)[0].strip()

    def _skip(self, rel, reason, src=None):
        """Remember a file that was left out, with its size and checksum so the original can still be matched."""
        entry = {"path": rel, "reason": reason}
        if src and os.path.isfile(src) and not os.path.islink(src):
            try:
                entry["size"] = os.path.getsize(src)
                if entry["size"] <= 2 << 30 and reason != "secret-looking name":
                    entry["sha256"] = sha256_file(src)
            except OSError:
                pass
        self.skipped.append(entry)

    def store(self, src, rel, log=False):
        """Copy one file to dest/rel. `log` files over the limit keep their head and tail (original checksum noted)."""
        parts = rel.split("/")
        if len(rel) > MAX_REL_PATH or any(p in (".", "..") or not SEG_RE.match(p) for p in parts):
            return self._skip(rel[:200], "name not allowed")
        st = os.lstat(src)
        if not stat.S_ISREG(st.st_mode):  # SECURITY: no symlinks, devices or pipes (CWE-59)
            return self._skip(rel, "not a regular file")
        if SKIP_FILE_RE.search(parts[-1]):
            return self._skip(rel, "secret-looking name", src)
        if WEIGHTS_RE.search(parts[-1]):
            return self._skip(rel, "model weights or image archive (name and checksum recorded instead)", src)
        size = st.st_size
        if size > self.max_file and not log or size > 2 << 30:
            return self._skip(rel, "larger than the per-file limit", src)
        with open(src, "rb") as f:
            data = f.read()
        if is_text(data):
            text = data.decode("utf-8")
            if len(data) > self.max_file:
                half = self.max_file // 2
                self.shortened.append({"path": rel, "size": size, "sha256": hashlib.sha256(data).hexdigest(),
                                       "kept": "first and last %d bytes" % half})
                text = (data[:half].decode("utf-8", "ignore") + "\n\n[... history_test: middle of the log left out, "
                        "original size %d bytes, SHA-256 in manifest.json ...]\n\n" % size
                        + data[-half:].decode("utf-8", "ignore"))
            text, counts = redact(text, self.extra)
            if counts:
                self.redactions[rel] = counts
            data = text.encode("utf-8")
        elif size > self.max_file:
            return self._skip(rel, "binary file larger than the per-file limit", src)
        if self.total + len(data) > self.max_run:
            return self._skip(rel, "run size limit reached", src)
        out = os.path.join(self.dest, *parts)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "wb") as f:
            f.write(data)
        self.total += len(data)

    def add_tree(self, src, part):
        """Copy a folder into part/, keeping its layout. Symlinked folders are not entered (CWE-59)."""
        if os.path.islink(src) or not os.path.isdir(src):
            die("not a folder: " + os.path.basename(src))
        for base, dirs, files in os.walk(src, followlinks=False):
            for d in sorted(dirs):
                if d in SKIP_DIRS:
                    self.skipped.append({"path": part + "/" + os.path.relpath(os.path.join(base, d), src).replace(
                        os.sep, "/")[:150], "reason": "dependency, cache or repository folder"})
            dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not os.path.islink(os.path.join(base, d)))
            for name in sorted(files):
                full = os.path.join(base, name)
                self.store(full, part + "/" + os.path.relpath(full, src).replace(os.sep, "/"))

    def add_path(self, src, part, log=False):
        """Copy a file (into part/) or a folder (into part/<folder name>/)."""
        if os.path.isdir(src) and not os.path.islink(src):
            name = os.path.basename(os.path.abspath(src))
            if not SEG_RE.match(name):
                die("folder name not allowed: " + name[:40])
            self.add_tree(src, part + "/" + name)
        elif os.path.isfile(src) and not os.path.islink(src):
            self.store(src, part + "/" + os.path.basename(src), log=log)
        else:
            die("not a regular file or folder: " + os.path.basename(src))


def list_files(folder):
    """All files under folder as sorted relative POSIX paths (symlinks are listed, never followed)."""
    out = []
    for base, dirs, files in os.walk(folder, followlinks=False):
        dirs.sort()
        for name in files:
            out.append(os.path.relpath(os.path.join(base, name), folder).replace(os.sep, "/"))
    return sorted(out)


def read_small(path, limit=4 << 20):
    """Read a stored text file for diffing; None when it is binary, missing or large."""
    try:
        if os.path.getsize(path) > limit:
            return None
        with open(path, "rb") as f:
            data = f.read()
    except OSError:
        return None
    return data.decode("utf-8").splitlines(keepends=True) if is_text(data) else None


def make_diff(folder, limit):
    """Write projects/diff.patch: unified diff from projects/input to projects/output (stored, redacted copies).

    Returns the number of files that differ, or None when one of the two projects is absent.
    Security: the projects are only read as text and compared, never executed.
    """
    a, b = os.path.join(folder, "projects", "input"), os.path.join(folder, "projects", "output")
    if not (os.path.isdir(a) and os.path.isdir(b)):
        return None
    out, changed = [], 0
    for rel in sorted(set(list_files(a)) | set(list_files(b))):
        fa, fb = os.path.join(a, *rel.split("/")), os.path.join(b, *rel.split("/"))
        ea, eb = os.path.isfile(fa), os.path.isfile(fb)
        if ea and eb and sha256_file(fa) == sha256_file(fb):
            continue
        changed += 1
        ta, tb = (read_small(fa) if ea else []), (read_small(fb) if eb else [])
        if ta is None or tb is None:
            out.append("Binary or large file differs: %s\n" % rel)
            continue
        out.extend(difflib.unified_diff(ta, tb, "input/" + rel if ea else "/dev/null",
                                        "output/" + rel if eb else "/dev/null"))
        if out and not out[-1].endswith("\n"):
            out[-1] += "\n\\ No newline at end of file\n"
    text = "".join(out) or "# No differences between projects/input and projects/output.\n"
    if len(text.encode("utf-8")) > limit:
        text = text[:limit] + "\n# history_test: diff shortened; compare projects/input and projects/output.\n"
    write_text(os.path.join(folder, "projects", "diff.patch"), text)
    return changed


def count_results(text):
    """Best-effort pass/fail/skip counts from a test log (Python unittest, Go test). Returns a dict or None.

    The counts are a convenience for the index; the saved log is the evidence. Explicit --passed/--failed/--skipped
    always win. Units: tests for unittest and `go test -v`, packages for plain `go test`.
    """
    ran = [int(n) for n in re.findall(r"(?m)^Ran (\d+) tests? in ", text)]
    if ran:
        bad = sum(int(n) for n in re.findall(r"(?m)^FAILED \([^)\n]*?failures=(\d+)", text))
        bad += sum(int(n) for n in re.findall(r"(?m)^FAILED \([^)\n]*?errors=(\d+)", text))
        skip = sum(int(n) for n in re.findall(r"(?m)^(?:OK|FAILED) \([^)\n]*?skipped=(\d+)", text))
        return {"passed": max(sum(ran) - bad - skip, 0), "failed": bad, "skipped": skip, "unit": "tests"}
    marks = re.findall(r"(?m)^\s*--- (PASS|FAIL|SKIP): ", text)
    if marks:
        return {"passed": marks.count("PASS"), "failed": marks.count("FAIL"), "skipped": marks.count("SKIP"),
                "unit": "tests"}
    ok, bad = len(re.findall(r"(?m)^ok\s+\S+", text)), len(re.findall(r"(?m)^FAIL\s+\S+", text))
    if ok or bad:
        return {"passed": ok, "failed": bad, "skipped": len(re.findall(r"(?m)^\?\s+\S+\s+\[no test files\]", text)),
                "unit": "packages"}
    return None


