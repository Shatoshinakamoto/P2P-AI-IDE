    def common(s):
        s.add_argument("--area", required=True, help="short tag: gateway, node-go, web, autopilot, toolkits, release ...")
        s.add_argument("--title", default="", help="one line: what this run was")
        s.add_argument("--kind", choices=KINDS, default="other")
        s.add_argument("--machine", choices=sorted(MACHINES), default="cloud", help="where the test ran")
